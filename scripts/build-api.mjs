#!/usr/bin/env node
/**
 * Builds the serverless API function into `api/index.js`.
 *
 * Why a bundle instead of letting Vercel compile TypeScript:
 *
 *   Vercel's Node builder runs `tsc` for `api/**` with its own generated
 *   tsconfig. That config does not enable `allowImportingTsExtensions`, so
 *   relative imports between `server/*.ts` files are emitted verbatim
 *   (`import ... from '../server/app.ts'`) and its file tracer then fails to
 *   follow the graph — the function shipped without `server/db.js`,
 *   `express` or `pg` and died with FUNCTION_INVOCATION_FAILED on every
 *   request. Extension-less imports failed the same way (ESM cannot resolve
 *   them).
 *
 *   esbuild bundles the whole graph (Express, pg, the schema DDL) into one
 *   self-contained ESM file, so the deployed function has no resolution work
 *   left to do. The output is committed so the file always exists when Vercel
 *   looks for entrypoints, and regenerated on every build.
 *
 * Run: node scripts/build-api.mjs
 */
import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// `--outfile <path>` lets tests regenerate into a temp file and diff it.
const outfileFlag = process.argv.indexOf('--outfile');
const outfile =
  outfileFlag === -1 ? path.join(root, 'api/index.js') : path.resolve(process.argv[outfileFlag + 1]);

await mkdir(path.dirname(outfile), { recursive: true });

const result = await build({
  entryPoints: [path.join(root, 'server/handler.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node24',
  // pg optionally requires pg-native; it is absent by design (pure JS client).
  external: ['pg-native'],
  logLevel: 'warning',
  // Bundled CommonJS dependencies call `require` at runtime; in an ESM file it
  // has to be recreated. esbuild's internal `__require` picks up this binding.
  banner: {
    js: "import { createRequire as __createRequire } from 'node:module';\nconst require = __createRequire(import.meta.url);",
  },
  metafile: true,
});

const entry = Object.keys(result.metafile.outputs)[0];
const { bytes } = result.metafile.outputs[entry];
const source = await readFile(outfile, 'utf8');
await writeFile(
  outfile,
  `// Generated by scripts/build-api.mjs from server/handler.ts — do not edit.\n${source}`,
);
console.log(`api/index.js: ${(bytes / 1024).toFixed(1)} kB, ${result.metafile.outputs[entry].imports.length} imports`);
